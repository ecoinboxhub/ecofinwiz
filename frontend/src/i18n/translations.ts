function getNestedValue(obj: TranslationKeys, path: string): string {
  const keys = path.split(".");
  let current: any = obj;
  for (const key of keys) {
    if (current && typeof current === "object" && key in current) {
      current = current[key];
    } else {
      return path;
    }
  }
  return typeof current === "string" ? current : path;
}

function formatString(template: string, ...args: (string | number)[]): string {
  return template.replace(/\$\{(\d+)\}/g, (_, index) => {
    const i = parseInt(index);
    return i < args.length ? String(args[i]) : `\${${index}}`;
  });
}

function deepMerge(target: TranslationKeys, source: TranslationKeys): TranslationKeys {
  const result: TranslationKeys = {};
  for (const key of Object.keys(target)) {
    if (typeof target[key] === "object" && target[key] !== null && typeof source[key] === "object" && source[key] !== null) {
      result[key] = deepMerge(target[key] as TranslationKeys, source[key] as TranslationKeys);
    } else {
      result[key] = (source[key] !== undefined ? source[key] : target[key]) as string;
    }
  }
  for (const key of Object.keys(source)) {
    if (!(key in target)) {
      result[key] = source[key] as string;
    }
  }
  return result;
}

